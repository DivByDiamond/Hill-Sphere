package dev.loki.hillsphere.mixin.particle;

import dev.loki.hillsphere.client.particle.Leanable;

import net.minecraft.client.particle.Particle;
import net.minecraft.client.particle.ParticleEngine;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** Every particle passes here once, fully built, before it joins the world: the moment to turn its launch speed. */
@Mixin(ParticleEngine.class)
public abstract class ParticleAddMixin {

    @Inject(method = "add", at = @At("HEAD"))
    private void hillsphereLean(Particle particle, CallbackInfo ci) {

        ((Leanable) particle).hillsphereLean();
    }
}
